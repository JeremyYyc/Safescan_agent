import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const dir=path.dirname(fileURLToPath(import.meta.url));
const rows=JSON.parse(await fs.readFile(path.join(dir,'workbook_input.json'),'utf8'));
const wb=Workbook.create();
const sh=wb.worksheets.add('文档总表');
const area=sh.getRange(`A1:K${rows.length}`);
area.values=rows;
area.format.font={name:'Arial',size:11};
area.format.wrapText=true;
area.format.verticalAlignment='center';
area.format.columnWidth=22;
sh.getRange('A:A').format.columnWidth=31;
sh.getRange('B:B').format.columnWidth=38;
sh.getRange('C:C').format.columnWidth=28;
sh.getRange('G:G').format.columnWidth=40;
sh.getRange('H:I').format.columnWidth=42;
sh.getRange('J:K').format.columnWidth=70;
sh.tables.add(`A1:K${rows.length}`,true,'KnowledgeDocuments');
sh.getRange('A1:K1').format.fill='#234A60';
sh.getRange('A1:K1').format.font={name:'Arial',size:11,bold:true,color:'#FFFFFF'};
area.format.autofitRows();
sh.freezePanes.freezeRows(1);
sh.showGridLines=false;
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'文档总表!A1:F5',include:'values',tableMaxRows:5,tableMaxCols:6,maxChars:1800})).ndjson);
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?',options:{useRegex:true,maxResults:10},maxChars:300})).ndjson);
const pic=await wb.render({sheetName:'文档总表',range:'A1:G12',scale:1,format:'png'});
await fs.writeFile(path.join(dir,'table-preview.png'),new Uint8Array(await pic.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(path.join(dir,'总表.xlsx'));
