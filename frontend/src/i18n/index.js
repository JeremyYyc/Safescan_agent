const enUS = {
  "Switch to English": "English",
  "Switch to Chinese": "中文",
};

const resources = { "zh-CN": zhCN, "en-US": enUS };

export function getLocale() {
  if (typeof window === "undefined") return defaultLocale;
  const saved = window.localStorage.getItem(localeStorageKey);
  return supportedLocales.includes(saved) ? saved : defaultLocale;
}

export function setLocale(locale) {
  if (!supportedLocales.includes(locale)) return false;
  window.localStorage.setItem(localeStorageKey, locale);
  window.location.reload();
  return true;
}

export function t(key, values = {}) {
  const template = resources[getLocale()]?.[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}

export function formatDateTime(value) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat(getLocale(), {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).format(date);
}
